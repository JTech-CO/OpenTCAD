import {createRequire} from "node:module";
import {mkdirSync,writeFileSync} from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
const require = createRequire(import.meta.url);
const {chromium} = require(process.env.OPENTCAD_PLAYWRIGHT_MODULE || "playwright");
const url = new URL(process.env.OPENTCAD_BROWSER_TEST_URL);
if (url.protocol !== "http:" || url.hostname !== "127.0.0.1" || !url.hash.startsWith("#experiment=")) throw new Error("Explicit private loopback test URL required");
const output = process.argv[2];
if (!output || !path.isAbsolute(output)) throw new Error("New absolute output directory required");
mkdirSync(output);
const browser = await chromium.launch({headless:true});
const checks = [];
try {
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  await context.route("**/*",route => new URL(route.request().url()).origin === url.origin ? route.continue() : route.abort());
  const page = await context.newPage();
  await page.goto(url.href);
  await page.getByRole("heading",{name:"Instant NMOS calculator"}).waitFor();
  assert.equal(new URL(page.url()).hash,"#lab");
  const before = await page.getByTestId("calculated-current").textContent();
  await page.getByRole("spinbutton",{name:/Channel width/}).fill("20");
  assert.notEqual(await page.getByTestId("calculated-current").textContent(),before);
  checks.push("English calculator responds to parameter change; token scrubbed from URL");
  await page.getByRole("button",{name:"Run DEVSIM solve",exact:true}).click();
  await page.getByText("Solve complete",{exact:true}).waitFor({timeout:120000});
  await page.getByRole("button",{name:"Run 2D MOSFET",exact:true}).click();
  await page.getByText("2D solve complete",{exact:true}).waitFor({timeout:120000});
  checks.push("Actual PN and 2D MOSFET complete through browser and local service");
  await page.getByRole("button",{name:"Refresh history"}).click();
  await page.getByRole("button",{name:"Open result"}).last().click();
  await page.getByText("Stored I-V",{exact:true}).waitFor();
  await page.screenshot({path:path.join(output,"history-en.png"),fullPage:false});
  checks.push("Stored 2D result reopens with mesh and I-V without submitting a new solve");
  await page.getByRole("button",{name:"한국어",exact:true}).click();
  await page.getByRole("heading",{name:"실행 이력과 결과 비교"}).waitFor();
  await page.getByRole("button",{name:"비교 기준으로 지정"}).click();
  await page.getByText("ΔI",{exact:true}).waitFor();
  await page.screenshot({path:path.join(output,"history-ko.png"),fullPage:false});
  checks.push("Korean history and comparison retain the selected solver result");
  await page.setViewportSize({width:390,height:844});
  await page.getByRole("button",{name:"이력·비교",exact:true}).click();
  await page.screenshot({path:path.join(output,"history-mobile.png"),fullPage:false});
  const layout = await page.evaluate(() => ({width:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
  assert.ok(layout.scroll <= layout.width+1,"Unexpected whole-page horizontal overflow");
  checks.push("390px viewport has no whole-page horizontal overflow");
  const retained = await page.locator('section[aria-label="실행 이력"] tbody tr').count();
  await page.reload();
  await page.getByRole("button",{name:"이력 새로고침"}).waitFor();
  assert.equal(await page.getByRole("button",{name:"이력 새로고침"}).isEnabled(),false);
  await page.goto(url.href);
  await page.getByRole("button",{name:"이력 새로고침"}).click();
  await page.locator('section[aria-label="실행 이력"] tbody tr').first().waitFor();
  assert.equal(await page.locator('section[aria-label="실행 이력"] tbody tr').count(),retained);
  checks.push("Refresh does not persist bearer credentials; reopening the private URL retrieves retained history");
  writeFileSync(path.join(output,"report.json"),JSON.stringify({passed:true,checks,releaseApproved:false},null,2),{flag:"wx"});
  console.log(JSON.stringify({passed:true,checks}));
} catch (error) {
  writeFileSync(path.join(output,"report.json"),JSON.stringify({passed:false,checks,releaseApproved:false},null,2),{flag:"wx"});
  throw error;
} finally {await browser.close();}
