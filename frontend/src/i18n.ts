export function getInitialLocale(): Locale {
  try {
    const saved = window.localStorage.getItem("opentcad-locale");
    if (saved === "en" || saved === "ko") {
      return saved;
    }
  } catch {
    // A blocked preference store must not prevent the app from starting.
  }

  return "en";
}
